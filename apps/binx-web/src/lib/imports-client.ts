import type { Schemas } from "@/lib/api-types";

export type ImportKind =
  | "clients"
  | "team"
  | "leads"
  | "projects"
  | "tasks"
  | "time_entries";

/** Everything that can be downloaded — the import kinds plus two export-only ones. */
export type ExportKind = ImportKind | "invoices" | "proposals";

export type DataFileFormat = "csv" | "xlsx";

export const IMPORT_KINDS: readonly ImportKind[] = [
  "clients",
  "team",
  "leads",
  "projects",
  "tasks",
  "time_entries",
];

export const EXPORT_KINDS: readonly ExportKind[] = [
  ...IMPORT_KINDS,
  "invoices",
  "proposals",
];

export function isImportKind(value: string): value is ImportKind {
  return (IMPORT_KINDS as readonly string[]).includes(value);
}

export function isExportKind(value: string): value is ExportKind {
  return (EXPORT_KINDS as readonly string[]).includes(value);
}

/** The download route for an export (proxied by app/api/agencies/[agencyId]/exports/[kind]). */
export function exportHref(
  agencyId: string,
  kind: ExportKind,
  format: DataFileFormat,
): string {
  return `/api/agencies/${encodeURIComponent(agencyId)}/exports/${kind}?format=${format}`;
}
export type ImportParseResult = Schemas["ImportParseRead"];
export type ImportResult = Schemas["ImportResultRead"];
export type ImportRowResult = Schemas["ImportRowResult"];
export type ImportField = Schemas["ImportFieldRead"];

/** One spreadsheet row with its cells assigned to import fields (field key → value). */
export type MappedImportRow = { row: number } & Record<
  string,
  string | number | null
>;

/** Column index per field key; null = not imported. */
export type ImportMapping = Record<string, number | null>;

/**
 * A starter file for an import, generated by binx-api from the import's own
 * fields — so its headers always map to every field automatically.
 */
export function importTemplateHref(
  agencyId: string,
  kind: ImportKind,
  format: DataFileFormat,
): string {
  return `/api/agencies/${encodeURIComponent(agencyId)}/imports/${kind}/template?format=${format}`;
}

/** Applies a column mapping to the parsed rows, producing what `runImport` sends. */
export function applyImportMapping(
  parsed: ImportParseResult,
  mapping: ImportMapping,
): MappedImportRow[] {
  return parsed.rows.map(({ row, cells }) => {
    const mapped: MappedImportRow = { row };
    for (const field of parsed.fields) {
      const column = mapping[field.key];
      mapped[field.key] =
        column === null || column === undefined
          ? null
          : (cells[column] ?? null);
    }
    return mapped;
  });
}

/** The required fields that still have no column assigned. */
export function missingRequiredFields(
  fields: ImportField[],
  mapping: ImportMapping,
): ImportField[] {
  return fields.filter(
    (field) =>
      field.required &&
      (mapping[field.key] === null || mapping[field.key] === undefined),
  );
}
