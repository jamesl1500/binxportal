"""Service layer for recurring invoice schedules (retainers).

Invoices are generated by a background job (``run_recurring_loop``, started
from main.py's lifespan) that checks every few minutes for schedules whose
``next_run_date`` has arrived, so a retainer bills on its date even when
nobody opens the app. Opening the Recurring Invoices list also catches up
the agency's due schedules on the spot (``catch_up_due_schedules``), and
``run_schedule_now`` bills one schedule's next period immediately. All three
claim a period before billing it (see "Generation" below), so a period is
never billed twice.
"""

from __future__ import annotations

import asyncio
import logging
import uuid
from calendar import monthrange
from datetime import UTC, date, datetime, timedelta
from decimal import ROUND_HALF_UP, Decimal

from fastapi import HTTPException, status
from sqlalchemy import delete, select, update
from sqlalchemy.ext.asyncio import AsyncSession

from binx_api.core.database import async_session_factory
from binx_api.core.errors import capture_error
from binx_api.modules.agencies import service as agencies_service
from binx_api.modules.agencies.models import Agency, AgencyClient
from binx_api.modules.invoicing import service as invoicing_service
from binx_api.modules.invoicing.models import Invoice, RecurringInvoiceLineItem, RecurringInvoiceSchedule
from binx_api.modules.invoicing.recurring_schemas import RecurringLineItemInput
from binx_api.modules.invoicing.schemas import LineItemInput
from binx_api.modules.projects.models import Project
from binx_api.modules.services import service as services_service
from binx_api.modules.users.models import User
from binx_api.modules.users.service import get_user_by_id

logger = logging.getLogger(__name__)

# The job's cadence. Schedules are due by date, so checking every 15
# minutes bills a period within minutes of midnight UTC on its day.
RECURRING_FIRST_DELAY_SECONDS = 60
RECURRING_EVERY_SECONDS = 15 * 60


def _clamp_day(year: int, month: int, day: int) -> int:
    return min(day, monthrange(year, month)[1])


def _first_run_date(
    *, interval: str, interval_count: int, day_of_month: int | None, weekday: int | None, start: date
) -> date:
    if interval == "monthly":
        assert day_of_month is not None
        candidate = date(start.year, start.month, _clamp_day(start.year, start.month, day_of_month))
        if candidate < start:
            candidate = _advance_monthly(candidate, interval_count, day_of_month)
        return candidate
    assert weekday is not None
    delta = (weekday - start.weekday()) % 7
    return start + timedelta(days=delta)


def _advance_monthly(current: date, interval_count: int, day_of_month: int) -> date:
    month_index = (current.year * 12 + (current.month - 1)) + interval_count
    year, month = divmod(month_index, 12)
    month += 1
    return date(year, month, _clamp_day(year, month, day_of_month))


def _advance(schedule: RecurringInvoiceSchedule) -> date:
    if schedule.interval == "monthly":
        assert schedule.day_of_month is not None
        return _advance_monthly(schedule.next_run_date, schedule.interval_count, schedule.day_of_month)
    return schedule.next_run_date + timedelta(weeks=schedule.interval_count)


async def _get_project_or_404(db: AsyncSession, agency_id: uuid.UUID, project_id: uuid.UUID | None) -> None:
    if project_id is None:
        return
    result = await db.execute(select(Project.id).where(Project.id == project_id, Project.agency_id == agency_id))
    if result.scalar_one_or_none() is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Project not found")


async def get_schedule_or_404(
    db: AsyncSession, agency_id: uuid.UUID, schedule_id: uuid.UUID
) -> RecurringInvoiceSchedule:
    result = await db.execute(
        select(RecurringInvoiceSchedule).where(
            RecurringInvoiceSchedule.id == schedule_id, RecurringInvoiceSchedule.agency_id == agency_id
        )
    )
    schedule = result.scalar_one_or_none()
    if schedule is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Recurring schedule not found")
    return schedule


async def list_line_items(db: AsyncSession, schedule_id: uuid.UUID) -> list[RecurringInvoiceLineItem]:
    result = await db.execute(
        select(RecurringInvoiceLineItem)
        .where(RecurringInvoiceLineItem.schedule_id == schedule_id)
        .order_by(RecurringInvoiceLineItem.position)
    )
    return list(result.scalars().all())


async def _replace_line_items(
    db: AsyncSession, schedule: RecurringInvoiceSchedule, line_items: list[RecurringLineItemInput]
) -> list[RecurringInvoiceLineItem]:
    await services_service.validate_service_ids(db, schedule.agency_id, (item.service_id for item in line_items))
    await db.execute(
        delete(RecurringInvoiceLineItem)
        .where(RecurringInvoiceLineItem.schedule_id == schedule.id)
        .execution_options(synchronize_session=False)
    )
    rows: list[RecurringInvoiceLineItem] = []
    for position, item in enumerate(line_items):
        row = RecurringInvoiceLineItem(
            schedule_id=schedule.id,
            position=position,
            description=item.description,
            quantity=item.quantity,
            unit_price_cents=item.unit_price_cents,
            service_id=item.service_id,
        )
        db.add(row)
        rows.append(row)
    return rows


def estimated_amount_cents(line_items: list[RecurringInvoiceLineItem]) -> int:
    return sum(
        int((Decimal(item.quantity) * Decimal(item.unit_price_cents)).quantize(Decimal("1"), rounding=ROUND_HALF_UP))
        for item in line_items
    )


async def create_schedule(
    db: AsyncSession,
    agency: Agency,
    *,
    created_by: User,
    client_id: uuid.UUID,
    project_id: uuid.UUID | None,
    title: str,
    interval: str,
    interval_count: int,
    day_of_month: int | None,
    weekday: int | None,
    due_days: int,
    tax_rate_percent: Decimal,
    notes: str | None,
    payment_instructions: str | None,
    auto_issue: bool,
    start_date: date | None,
    line_items: list[RecurringLineItemInput],
) -> RecurringInvoiceSchedule:
    await agencies_service.get_client_or_404(db, agency.id, client_id)
    await _get_project_or_404(db, agency.id, project_id)

    next_run = _first_run_date(
        interval=interval,
        interval_count=interval_count,
        day_of_month=day_of_month,
        weekday=weekday,
        start=start_date or datetime.now(UTC).date(),
    )

    schedule = RecurringInvoiceSchedule(
        agency_id=agency.id,
        client_id=client_id,
        project_id=project_id,
        created_by_id=created_by.id,
        title=title,
        interval=interval,
        interval_count=interval_count,
        day_of_month=day_of_month,
        weekday=weekday,
        due_days=due_days,
        tax_rate_percent=tax_rate_percent,
        notes=notes,
        payment_instructions=payment_instructions,
        auto_issue=auto_issue,
        next_run_date=next_run,
    )
    db.add(schedule)
    await db.flush()
    await _replace_line_items(db, schedule, line_items)
    await db.commit()
    await db.refresh(schedule)
    return schedule


async def update_schedule(
    db: AsyncSession,
    schedule: RecurringInvoiceSchedule,
    *,
    client_id: uuid.UUID,
    project_id: uuid.UUID | None,
    title: str,
    interval: str,
    interval_count: int,
    day_of_month: int | None,
    weekday: int | None,
    due_days: int,
    tax_rate_percent: Decimal,
    notes: str | None,
    payment_instructions: str | None,
    auto_issue: bool,
    start_date: date | None,
    line_items: list[RecurringLineItemInput],
) -> RecurringInvoiceSchedule:
    await agencies_service.get_client_or_404(db, schedule.agency_id, client_id)
    await _get_project_or_404(db, schedule.agency_id, project_id)

    schedule.client_id = client_id
    schedule.project_id = project_id
    schedule.title = title
    schedule.interval = interval
    schedule.interval_count = interval_count
    schedule.day_of_month = day_of_month
    schedule.weekday = weekday
    schedule.due_days = due_days
    schedule.tax_rate_percent = tax_rate_percent
    schedule.notes = notes
    schedule.payment_instructions = payment_instructions
    schedule.auto_issue = auto_issue
    # Only re-anchor next_run_date if the caller explicitly gave a new
    # start_date — otherwise editing a schedule's price shouldn't reset when
    # its next invoice goes out.
    if start_date is not None:
        schedule.next_run_date = _first_run_date(
            interval=interval,
            interval_count=interval_count,
            day_of_month=day_of_month,
            weekday=weekday,
            start=start_date,
        )

    await _replace_line_items(db, schedule, line_items)
    await db.commit()
    await db.refresh(schedule)
    return schedule


async def set_active(
    db: AsyncSession, schedule: RecurringInvoiceSchedule, *, is_active: bool
) -> RecurringInvoiceSchedule:
    schedule.is_active = is_active
    await db.commit()
    await db.refresh(schedule)
    return schedule


async def delete_schedule(db: AsyncSession, schedule: RecurringInvoiceSchedule) -> None:
    await db.delete(schedule)
    await db.commit()


async def list_schedules(
    db: AsyncSession, agency_id: uuid.UUID, *, client_id: uuid.UUID | None = None
) -> list[tuple[RecurringInvoiceSchedule, str, str | None]]:
    query = (
        select(RecurringInvoiceSchedule, AgencyClient.name, Project.name)
        .join(AgencyClient, AgencyClient.id == RecurringInvoiceSchedule.client_id)
        .outerjoin(Project, Project.id == RecurringInvoiceSchedule.project_id)
        .where(RecurringInvoiceSchedule.agency_id == agency_id)
    )
    if client_id is not None:
        query = query.where(RecurringInvoiceSchedule.client_id == client_id)
    query = query.order_by(RecurringInvoiceSchedule.next_run_date)
    rows = (await db.execute(query)).all()
    return [(schedule, client_name, project_name) for schedule, client_name, project_name in rows]


# ---- Generation ---------------------------------------------------------------
#
# Every path that bills a period (the background job, the list page's
# catch-up, "Generate now") first *claims* it: lock the schedule row, move
# next_run_date on, and commit. Only then is the invoice built. Creating the
# invoice commits several times, so a lock alone wouldn't cover it, and two
# processes (or a page load racing the job) could otherwise both bill the
# same period. If building the invoice fails, the claim is handed back, so
# the next run tries that period again instead of silently skipping it.


async def _claim(db: AsyncSession, schedule: RecurringInvoiceSchedule) -> date:
    """Advances an already-locked schedule past its next period and commits.
    Returns the claimed period's date (the invoice's issue date)."""
    period = schedule.next_run_date
    schedule.next_run_date = _advance(schedule)
    schedule.last_run_at = datetime.now(UTC)
    await db.commit()
    return period


async def _release(db: AsyncSession, schedule_id: uuid.UUID, *, period: date, claimed_next: date) -> None:
    """Hands a claimed period back after a failure. Conditional, so it never
    rewinds a schedule someone has changed since."""
    await db.execute(
        update(RecurringInvoiceSchedule)
        .where(RecurringInvoiceSchedule.id == schedule_id, RecurringInvoiceSchedule.next_run_date == claimed_next)
        .values(next_run_date=period)
    )
    await db.commit()


async def _generate_for_period(db: AsyncSession, schedule: RecurringInvoiceSchedule, period: date) -> Invoice:
    rows = await list_line_items(db, schedule.id)
    line_items = [
        LineItemInput(
            description=r.description, quantity=r.quantity, unit_price_cents=r.unit_price_cents, service_id=r.service_id
        )
        for r in rows
    ]
    agency = await db.get(Agency, schedule.agency_id)
    assert agency is not None
    created_by = await get_user_by_id(db, schedule.created_by_id) if schedule.created_by_id else None

    invoice = await invoicing_service.create_invoice(
        db,
        agency,
        created_by=created_by,
        client_id=schedule.client_id,
        project_id=schedule.project_id,
        issue_date=period,
        due_date=period + timedelta(days=schedule.due_days),
        discount_amount_cents=None,
        discount_percent=None,
        tax_rate_percent=schedule.tax_rate_percent,
        notes=schedule.notes,
        payment_instructions=schedule.payment_instructions,
        line_items=line_items,
    )
    if schedule.auto_issue:
        invoice = await invoicing_service.issue_invoice(db, invoice, issued_by=created_by) if created_by else invoice

    schedule.last_generated_invoice_id = invoice.id
    await db.commit()
    return invoice


async def _bill_claimed(db: AsyncSession, schedule: RecurringInvoiceSchedule, period: date) -> Invoice:
    """Builds the invoice for a claimed period, handing the claim back if
    that fails (and re-raising)."""
    schedule_id, claimed_next = schedule.id, schedule.next_run_date
    try:
        return await _generate_for_period(db, schedule, period)
    except Exception:
        await db.rollback()
        await _release(db, schedule_id, period=period, claimed_next=claimed_next)
        raise


async def run_schedule_now(db: AsyncSession, schedule: RecurringInvoiceSchedule) -> Invoice:
    """ "Generate now": bills the schedule's next period immediately,
    whatever its date, under the same claim as the job."""
    locked = await db.scalar(
        select(RecurringInvoiceSchedule)
        .where(RecurringInvoiceSchedule.id == schedule.id)
        .with_for_update()
        .execution_options(populate_existing=True)
    )
    if locked is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Schedule not found")
    if not locked.is_active:
        await db.commit()  # nothing changed; just releases the row lock
        raise HTTPException(status.HTTP_409_CONFLICT, "This schedule is paused")
    period = await _claim(db, locked)
    return await _bill_claimed(db, locked, period)


async def claim_next_due(
    db: AsyncSession, *, as_of: date, skip: set[uuid.UUID], agency_id: uuid.UUID | None = None
) -> tuple[RecurringInvoiceSchedule, date] | None:
    """Locks and claims the next active schedule whose period has arrived,
    leaving out ``skip`` and agencies on their deletion hold. SKIP LOCKED
    lets several processes (and page loads) work through the queue at once
    without ever claiming the same period twice. None when nothing is due."""
    query = (
        select(RecurringInvoiceSchedule)
        .join(Agency, Agency.id == RecurringInvoiceSchedule.agency_id)
        .where(
            RecurringInvoiceSchedule.is_active.is_(True),
            RecurringInvoiceSchedule.next_run_date <= as_of,
            Agency.deletion_scheduled_for.is_(None),
        )
    )
    if agency_id is not None:
        query = query.where(RecurringInvoiceSchedule.agency_id == agency_id)
    if skip:
        query = query.where(RecurringInvoiceSchedule.id.not_in(skip))
    schedule = await db.scalar(
        query.order_by(RecurringInvoiceSchedule.next_run_date)
        .limit(1)
        .with_for_update(of=RecurringInvoiceSchedule, skip_locked=True)
        .execution_options(populate_existing=True)
    )
    if schedule is None:
        # Commit, not rollback: the empty SELECT holds no locks, and a
        # rollback would expire every object the caller already holds (the
        # invoices generated earlier in this run).
        await db.commit()
        return None
    return schedule, await _claim(db, schedule)


async def _run_due(db: AsyncSession, *, as_of: date, agency_id: uuid.UUID | None) -> list[Invoice]:
    """Bills one period for every schedule due by ``as_of``. One period per
    schedule per run: a schedule that's several periods behind catches up
    one invoice per run rather than all at once. A failing schedule is
    reported and skipped, never blocking the rest."""
    generated: list[Invoice] = []
    skip: set[uuid.UUID] = set()
    while True:
        claimed = await claim_next_due(db, as_of=as_of, skip=skip, agency_id=agency_id)
        if claimed is None:
            return generated
        schedule, period = claimed
        # Read before billing: a failure rolls back, which expires the row.
        context = {"recurring_schedule_id": str(schedule.id), "agency_id": str(schedule.agency_id)}
        skip.add(schedule.id)
        try:
            generated.append(await _bill_claimed(db, schedule, period))
        except Exception as exc:  # noqa: BLE001 - reported; the claim was handed back for the next run
            await capture_error(exc, tags={"job": "recurring_invoices"}, context=context)


async def catch_up_due_schedules(db: AsyncSession, agency_id: uuid.UUID, *, as_of: date | None = None) -> list[Invoice]:
    """The list page's catch-up: bills whatever is due in this agency right
    away, so nobody waits for the next job run to see this month's invoice."""
    return await _run_due(db, as_of=as_of or datetime.now(UTC).date(), agency_id=agency_id)


async def generate_due_invoices(*, as_of: date | None = None) -> int:
    """The background job's pass over every agency. Returns how many
    invoices it created."""
    async with async_session_factory() as db:
        invoices = await _run_due(db, as_of=as_of or datetime.now(UTC).date(), agency_id=None)
    if invoices:
        logger.info("Generated %d recurring invoice(s)", len(invoices))
    return len(invoices)


async def run_recurring_loop() -> None:
    """Runs for the life of the API process, started from main.py's
    lifespan, so retainers bill on their date even when nobody opens the
    app."""
    await asyncio.sleep(RECURRING_FIRST_DELAY_SECONDS)
    while True:
        try:
            await generate_due_invoices()
        except Exception as exc:  # noqa: BLE001 - the loop has to outlive any one failure
            await capture_error(exc, tags={"job": "recurring_invoices"})
        await asyncio.sleep(RECURRING_EVERY_SECONDS)
