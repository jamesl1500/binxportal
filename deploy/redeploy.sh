#!/usr/bin/env bash
# Runs ON the EC2 instance, invoked remotely by GitHub Actions via
# `aws ssm send-command` (see .github/actions/ssm-redeploy) — never over SSH.
#
#   redeploy.sh <production|staging> <image-tag>      e.g. redeploy.sh staging sha-65234f6a1b2c
#
# Both environments live on this one box as separate compose projects
# (docker-compose.prod.yml / docker-compose.staging.yml). This pulls the
# given image tag for the chosen environment and recreates only the
# containers whose image actually changed; db/redis are untouched unless
# their own images changed. The compose files, the Caddyfile, and this
# script itself are unpacked into /binxportal by the same SSM command just
# before this runs, so the box always matches the commit being deployed.
#
# SAFETY: this must never become `down -v` / `down` — see the warning at the
# top of docker-compose.prod.yml. `up -d` after a `pull` is the whole deploy.
set -euo pipefail
cd /binxportal

TARGET="${1:?usage: redeploy.sh <production|staging> <image-tag>}"
TAG="${2:?usage: redeploy.sh <production|staging> <image-tag>}"

AWS_REGION=us-east-2
ECR_REGISTRY="574247905173.dkr.ecr.${AWS_REGION}.amazonaws.com"
EDGE_NETWORK=binxportal-edge
PROD_COMPOSE=(docker compose -f docker-compose.prod.yml)

case "$TARGET" in
  production)
    SECRET_ID=binxportal/app
    ENV_FILE=.env
    WEB_TAG="$TAG"
    COMPOSE=("${PROD_COMPOSE[@]}")
    APP_SERVICES=(api web)
    # The compose project/service names of the old in-box Postgres this
    # environment ran on before RDS — see migrate_to_rds below.
    PROJECT=binxportal
    API_SERVICE=api
    LEGACY_DB_SERVICE=db
    ;;
  staging)
    SECRET_ID=binxportal/staging
    ENV_FILE=.env.staging
    # binx-web is built once per environment (NEXT_PUBLIC_* are baked in at
    # build time) — the staging build is the same commit under this prefix.
    WEB_TAG="staging-$TAG"
    COMPOSE=(docker compose --env-file .env.staging -f docker-compose.staging.yml)
    APP_SERVICES=(staging-api staging-web)
    PROJECT=binxportal-staging
    API_SERVICE=staging-api
    LEGACY_DB_SERVICE=staging-db

    # Production fits in 2GB on its own; a second stack does not. Refuse
    # rather than let staging push the box into swap/OOM under production.
    mem_kb=$(awk '/^MemTotal:/ {print $2}' /proc/meminfo)
    if [ "$mem_kb" -lt 3500000 ]; then
      echo "ERROR: staging needs a 4GB instance (t4g.medium); this box has $((mem_kb / 1024))MB. Resize it first." >&2
      exit 1
    fi
    ;;
  *)
    echo "ERROR: unknown environment '$TARGET' (expected production or staging)" >&2
    exit 2
    ;;
esac

# The env file is regenerated on every deploy, not hand-placed — the real
# secrets live in Secrets Manager (see infra/lib/secrets-stack.ts and
# infra/lib/staging-stack.ts), fetched here via the instance's own IAM role.
# API_IMAGE/WEB_IMAGE/CADDY_IMAGE aren't secrets, so they're just computed below rather
# than stored anywhere. Nothing is sourced into this shell: compose reads the
# file itself, and keeping one environment's values out of the process env
# means they can't leak into a compose command for the other.
secret_json=$(aws secretsmanager get-secret-value --secret-id "$SECRET_ID" --region "$AWS_REGION" \
  --query SecretString --output text)

value=$(jq -r '.JWT_SECRET // empty' <<<"$secret_json")
if [ -z "$value" ] || [ "$value" = "REPLACE_ME" ]; then
  echo "ERROR: JWT_SECRET is not set in the $SECRET_ID secret (still the CDK placeholder?)" >&2
  exit 1
fi

# The database's credentials + endpoint, generated by CDK alongside the RDS
# instance itself (infra/lib/rds-stack.ts) — never set by hand, so there's
# no placeholder to check for, only whether the stack exists yet.
DB_SECRET_ID="binxportal/rds/$TARGET"
if ! db_json=$(aws secretsmanager get-secret-value --secret-id "$DB_SECRET_ID" --region "$AWS_REGION" \
  --query SecretString --output text); then
  echo "ERROR: no $DB_SECRET_ID secret — deploy infra's RDS stack for $TARGET first" >&2
  exit 1
fi
db_host=$(jq -r .host <<<"$db_json")
db_port=$(jq -r .port <<<"$db_json")
db_name=$(jq -r .dbname <<<"$db_json")
db_user=$(jq -r .username <<<"$db_json")
db_password=$(jq -r .password <<<"$db_json")

umask 077
{
  # A key still holding CDK's REPLACE_ME placeholder is left out entirely, so
  # it reads as unset (= that feature cleanly off) rather than as a bogus
  # value — SENTRY_DSN=REPLACE_ME, for one, would crash the API on boot.
  jq -r 'to_entries[] | select(.value != "REPLACE_ME") | "\(.key)=\(.value)"' <<<"$secret_json"
  # binx-api assembles DATABASE_URL from these (core/config.py). CDK's
  # generated password never contains `$`, quotes or whitespace (see
  # RdsStack's docstring), so it's safe unquoted in a compose env file.
  echo "DATABASE_ENDPOINT=${db_host}"
  echo "DATABASE_PORT=${db_port}"
  echo "DATABASE_NAME=${db_name}"
  echo "DATABASE_USERNAME=${db_user}"
  echo "DATABASE_PASSWORD=${db_password}"
  echo "API_IMAGE=${ECR_REGISTRY}/binx-api:${TAG}"
  echo "WEB_IMAGE=${ECR_REGISTRY}/binx-web:${WEB_TAG}"
  # Only docker-compose.prod.yml's caddy service reads this (it's shared —
  # fronts both environments), but computing it unconditionally here is
  # simpler than branching on $TARGET, and harmless for the staging env file.
  echo "CADDY_IMAGE=${ECR_REGISTRY}/binx-caddy:${TAG}"
} > "$ENV_FILE"

# Caddy is a production-project service, so every PROD_COMPOSE command below
# interpolates docker-compose.prod.yml from production's .env — not the
# staging env file just written. A staging deploy still updates the shared
# Caddy, so record its image there too; otherwise a box whose last production
# deploy predates the custom Caddy image has no CADDY_IMAGE in .env at all
# and compose refuses to parse the file.
if [ "$TARGET" != production ]; then
  if [ ! -f .env ]; then
    echo "ERROR: no production .env on this box — Caddy lives in the production compose project, so deploy production once first" >&2
    exit 1
  fi
  { grep -v '^CADDY_IMAGE=' .env || true; echo "CADDY_IMAGE=${ECR_REGISTRY}/binx-caddy:${TAG}"; } > .env.next
  mv .env.next .env
fi

aws ecr get-login-password --region "$AWS_REGION" | \
  docker login --username AWS --password-stdin "$ECR_REGISTRY"

# Shared by production's Caddy and the staging app containers. Owned by this
# script rather than either compose project (both declare it `external`).
docker network inspect "$EDGE_NETWORK" >/dev/null 2>&1 || docker network create "$EDGE_NETWORK"

# A pull can land mid-layer with "no space left on device" if the previous
# deploy's now-superseded images are still sitting around. Pruning before the
# pull, not just after, is what actually guarantees room; images still
# backing a running container (either environment's) are never touched by
# `prune`, so this can't take down what's currently live.
echo "==> Pruning unused images before pulling, to guarantee room for the new layers"
docker image prune -af

echo "==> Deploying $TARGET at $TAG"
"${COMPOSE[@]}" pull "${APP_SERVICES[@]}"

# One-time move from the environment's old in-box Postgres container (the
# `db` / `staging-db` service the compose files had before RDS) onto RDS,
# done by the first deploy that no longer has that service: stop the api so
# nothing writes mid-copy, dump the container, restore into RDS, check every
# table's row count matches. Runs after the pull so the api is only down for
# the copy itself; the `up -d` below then starts the new api on RDS and
# --remove-orphans removes the old db container. Its volume
# (<project>_db-data) is never touched — remove it by hand once satisfied.
#
# Refuses, before stopping anything, if RDS already has tables (a half-done
# earlier attempt, or the wrong database) — --single-transaction means a
# failed restore leaves it empty again, so just rerun the deploy. Any
# failure after the api stops restarts the old api on the old database.
MIGRATED_MARKER=".rds-migrated-$TARGET"
pg18=(docker run --rm -i --network host -e PGPASSWORD -e PGSSLMODE=require postgres:18-alpine)
on_rds() { PGPASSWORD="$db_password" "${pg18[@]}" "$@" -h "$db_host" -p "$db_port" -U "$db_user" -d "$db_name"; }
# Exact row count per public table, one "table|count" line each — compared
# before and after the restore.
ROW_COUNTS_SQL="select table_name, (xpath('/row/c/text()', query_to_xml(format('select count(*) as c from public.%I', table_name), false, true, '')))[1]::text from information_schema.tables where table_schema = 'public' and table_type = 'BASE TABLE' order by 1"

migrate_to_rds() {
  local legacy_db="$1" api_containers dump
  echo "==> Moving $TARGET's data from its Postgres container onto RDS ($db_host)"

  if [ "$(on_rds psql -tAc "select count(*) from pg_tables where schemaname = 'public'")" != 0 ]; then
    echo "ERROR: $DB_SECRET_ID's database already has tables — refusing to restore over it" >&2
    exit 1
  fi

  api_containers=$(docker ps -q --filter "label=com.docker.compose.project=$PROJECT" \
    --filter "label=com.docker.compose.service=$API_SERVICE")
  if [ -n "$api_containers" ]; then
    # shellcheck disable=SC2086 # one id per word
    trap 'echo "ERROR: move to RDS failed — restarting the old api on the old database" >&2; docker start '"$(echo $api_containers)"' >/dev/null' EXIT
    # shellcheck disable=SC2086
    docker stop $api_containers >/dev/null
  fi

  mkdir -p backups
  dump="backups/$TARGET-pre-rds-$(date -u +%Y%m%dT%H%M%SZ).dump"
  docker exec "$legacy_db" pg_dump -U binxapi -d binxportal -Fc > "$dump"
  on_rds pg_restore --no-owner --no-privileges --single-transaction --exit-on-error < "$dump"

  if ! diff <(docker exec "$legacy_db" psql -U binxapi -d binxportal -tAc "$ROW_COUNTS_SQL") \
            <(on_rds psql -tAc "$ROW_COUNTS_SQL"); then
    echo "ERROR: row counts differ between the container and RDS after the restore (diff above)" >&2
    exit 1
  fi

  trap - EXIT
  touch "$MIGRATED_MARKER"
  echo "==> Done — dump kept at /binxportal/$dump"
}

if [ ! -f "$MIGRATED_MARKER" ]; then
  legacy_db=$(docker ps -q --filter "label=com.docker.compose.project=$PROJECT" \
    --filter "label=com.docker.compose.service=$LEGACY_DB_SERVICE")
  if [ -n "$legacy_db" ]; then
    migrate_to_rds "$legacy_db"
  elif docker volume inspect "${PROJECT}_db-data" >/dev/null 2>&1; then
    echo "ERROR: ${PROJECT}_db-data exists but its Postgres container isn't running, so its data can't be moved to RDS." >&2
    echo "       Start it (docker start ${PROJECT}-${LEGACY_DB_SERVICE}-1) and redeploy, or, if that data isn't wanted, touch /binxportal/$MIGRATED_MARKER." >&2
    exit 1
  else
    # A fresh environment — nothing to carry over; alembic creates the schema.
    touch "$MIGRATED_MARKER"
  fi
fi

"${COMPOSE[@]}" up -d --remove-orphans

# Caddy belongs to the production project but fronts both environments, so a
# staging deploy refreshes it too. --no-deps: only Caddy — a staging deploy
# must never recreate production's api/web as a side effect. An explicit
# pull first: CADDY_IMAGE is now a moving sha-tagged image (not the stable
# caddy:2-alpine tag `up -d` could just reuse from cache before), same as
# the APP_SERVICES pull above.
"${PROD_COMPOSE[@]}" pull caddy
"${PROD_COMPOSE[@]}" up -d --no-deps caddy

if [ "$TARGET" = "staging" ]; then
  # Basic auth for staging.binxportal.com, generated from the secret so no
  # password hash is committed. Caddy does the bcrypt hashing itself.
  auth_user=$(jq -r '.STAGING_BASIC_AUTH_USER // empty' <<<"$secret_json")
  auth_password=$(jq -r '.STAGING_BASIC_AUTH_PASSWORD // empty' <<<"$secret_json")
  if [ -n "$auth_user" ] && [ -n "$auth_password" ]; then
    auth_hash=$("${PROD_COMPOSE[@]}" exec -T caddy caddy hash-password --plaintext "$auth_password")
    printf 'basic_auth {\n\t%s %s\n}\n' "$auth_user" "$auth_hash" > deploy/staging-auth.caddy
  else
    echo "WARNING: STAGING_BASIC_AUTH_USER/PASSWORD not set in $SECRET_ID — staging is publicly reachable (still noindex)"
    rm -f deploy/staging-auth.caddy
  fi
fi

# Validate before reloading: a reload that fails leaves the running config
# in place, but say so loudly rather than let a broken Caddyfile sit on disk
# waiting for the next container restart.
echo "==> Reloading Caddy"
"${PROD_COMPOSE[@]}" exec -T caddy caddy validate --config /etc/caddy/Caddyfile
for attempt in 1 2 3 4 5; do
  # Retried because a just-recreated Caddy's admin API takes a moment to listen.
  if "${PROD_COMPOSE[@]}" exec -T caddy caddy reload --config /etc/caddy/Caddyfile; then
    break
  fi
  [ "$attempt" -eq 5 ] && { echo "ERROR: caddy reload failed" >&2; exit 1; }
  sleep 2
done

echo "==> Pruning the now-superseded previous version's images"
docker image prune -af

echo "==> Current state"
"${PROD_COMPOSE[@]}" ps
if [ -f .env.staging ]; then
  docker compose --env-file .env.staging -f docker-compose.staging.yml ps
fi
